import * as d3 from 'd3';
import * as topojson from 'topojson-client';
import { CONFIG, STATE, flowVal, EST_MIN_REL_WIDTH } from './config.js';
import { TradeMap } from './map.js';

// Region codes used by the SHC region filter (UNCTADstat major regions).
const REGION_CODE = { Africa: '5100', Americas: '5200', Asia: '5300', Europe: '5400', Oceania: '5500' };

// Weight methods that are experimental estimates (not R reported, not C UN Comtrade's own estimate)
export const EST_WEIGHT_CODES = ['K', 'U', 'B', 'Q'];

// Row -> object for a list of column names (the same keys, in the same order, as before).
const _makers = new Map();
function rowMaker(cols) {
    const key = cols.join('');
    let f = _makers.get(key);
    if (!f) {
        try { f = new Function('r', `return {${cols.map((c, k) => `${JSON.stringify(c)}:r[${k}]`).join(',')}};`); }
        catch { f = r => { const o = {}; for (let k = 0; k < cols.length; k++) o[cols[k]] = r[k]; return o; }; }   // no eval allowed
        _makers.set(key, f);
    }
    return f;
}

export const DataLoader = {
    _flows: {},        // "PRODUCT|YEAR" -> array of flow objects
    _summary: {},      // PRODUCT -> summary json
    _visibility: null,

    async loadAll() {
        try {
            const [world, coords, meta, products, buildInfo] = await Promise.all([
                d3.json(CONFIG.geoJsonUrl),
                fetch('data/coords_shc.json').then(r => r.json()),
                fetch('data/meta.json').then(r => r.json()),
                fetch('data/products.json').then(r => r.json()),
                fetch('data/build_info.json').then(r => r.json()),
            ]);

            // Correct the ~11.314 deg westward longitude shift in the UNCTAD TopoJSON (as in SHC).
            if (world.transform) world.transform.translate[0] += 11.314;
            STATE.geoData = topojson.feature(world, world.objects.economies);
            STATE.borderLayers = {
                plain:      topojson.feature(world, world.objects['plain-borders']),
                dashed:     topojson.feature(world, world.objects['dashed-borders']),
                dotted:     topojson.feature(world, world.objects['dotted-borders']),
                dashDotted: topojson.feature(world, world.objects['dash-dotted-borders']),
            };
            STATE.countryPoints = world.objects['economies-point']
                ? topojson.feature(world, world.objects['economies-point']) : null;

            // Centroids from the map polygons, then SHC's curated coordinates where they exist.
            // (a centroid walks the whole polygon: only those that SHC's coordinates do not replace are computed)
            STATE.geoData.features.forEach(f => {
                const iso = TradeMap.isoMap[parseInt(f.properties.code, 10)];
                if (iso && !coords[iso]) STATE.countryCoords[iso] = d3.geoCentroid(f);
            });
            Object.entries(coords).forEach(([iso, e]) => { STATE.countryCoords[iso] = e.coords; });

            STATE.meta = meta;
            // labels as the UI writes codes (WORDING_REVIEW R5): "8507.10 + 8507.20" -> "8507.10, 8507.20" (products.json is generated by the pipeline)
            products.products?.forEach(p => { p.label = p.label.replace(/(\d) \+ (\d)/g, '$1, $2'); });
            STATE.products = products;
            STATE.buildInfo = buildInfo;
            meta.economies.forEach(e => {
                STATE.eco[e.iso] = e;
                STATE.countryNames[e.iso] = e.name;
            });
            return true;
        } catch (error) {
            console.error('DataLoader.loadAll error:', error);
            return false;
        }
    },

    product(id = STATE.product) {
        return STATE.products.products.find(p => p.id === id);
    },

    // Years a product has data for (SPENT_11..19 only exist in HS 2022, 2022-2024).
    productYears(id = STATE.product) {
        const [a, b] = this.product(id).years;
        return CONFIG.years.filter(y => y >= a && y <= b);
    },

    // Flows of one product and year. Columns are read by name (docs/overnight/DATA_CONTRACT.md).
    // Reported mode (default) returns `rows` only, exactly as v1. Estimated mode adds `erows`
    // (flows that exist only as estimates, src = "e").
    async loadFlows(product = STATE.product, year = STATE.year) {
        const key = `${product}|${year}`;
        // requests made at the same time (the entry page asks for the same file several times) share one fetch
        if (!this._flows[key]) await (this._pending[key] ||= this._fetchFlows(product, year, key));
        const f = this._flows[key];
        if (STATE.basis !== 'estimated') return f.rows;
        if (!f.both) f.both = f.rows.concat(f.erows);
        return f.both;
    },
    _pending: {},
    async _fetchFlows(product, year, key) {
        try {
            const res = await fetch(`data/flows/${product}/${year}.json`);
            if (!res.ok) { this._flows[key] = { rows: [], erows: [] }; }
            else {
                const js = await res.json();
                const c = js.cols;
                // one object literal per row, compiled from the column names: about five times faster than
                // setting the properties one by one (a question page or a year change decodes 9,000 rows)
                const obj = rowMaker(c);
                const rows = js.rows.map(obj);
                const erows = (js.erows || []).map(r => { const o = obj(r); o.src = 'e'; return o; });
                if (c.includes('ve')) this._hasEstCols = true;
                this._flows[key] = { rows, erows };
            }
        } finally { delete this._pending[key]; }
    },

    // What this build estimates (meta.estimation). Weight estimates may be absent while value
    // estimates exist; the UI must say so instead of implying estimates.
    valueEstAvailable() {
        const v = STATE.meta?.estimation?.value;
        return !!(v && v.method && v.method !== 'none');
    },
    weightEstAvailable() {
        const w = STATE.meta?.estimation?.weight;
        return !!(w && (w.available === true || (w.available == null && w.method && !['none', 'reported_only'].includes(w.method))));
    },
    estAvailableFor(metric = STATE.metric) {
        return metric === 'weight' ? this.weightEstAvailable() : this.valueEstAvailable();
    },
    // Estimated mode is on and the current measure has estimates in this build.
    estActive(metric = STATE.metric) {
        return STATE.basis === 'estimated' && this.estAvailableFor(metric);
    },

    // One sentence on the basis of the numbers, from the data state (footer, CSV).
    basisSentence() {
        if (STATE.basis !== 'estimated') return 'Values and weights as reported to UN Comtrade (some weights are UN Comtrade’s own estimates).';
        const v = this.valueEstAvailable(), w = this.weightEstAvailable();
        const vs = v ? 'Values: reported, or experimental estimates where marked est.' : 'No value estimates in this build; values are as reported.';
        const ws = w ? 'Weights: reported, or experimental estimates where marked est.' : 'No weight estimates in this build; weights are as reported.';
        return `${vs} ${ws}`;
    },

    // Estimates are offered when meta.json carries an active estimation block.
    estimationAvailable() {
        const e = STATE.meta?.estimation;
        if (!e) return false;
        const v = e.value && e.value.method && e.value.method !== 'none';
        const w = e.weight && (e.weight.available || (e.weight.method && e.weight.method !== 'none' && e.weight.method !== 'reported_only'));
        return !!(v || w);
    },

    // True when the metric value of flow d is a model estimate (only in estimated mode).
    isEst(d, metric = STATE.metric) {
        if (STATE.basis !== 'estimated' || !d) return false;
        if (!this.estAvailableFor(metric)) return false;
        if (d.src === 'e') return true;
        // C = UN Comtrade's own estimate: a reported weight, not an experimental estimate (DATA_CONTRACT 2.2)
        if (metric === 'weight') return EST_WEIGHT_CODES.includes(d.wm) && d.we != null && !this.nearlyReported(d, metric);
        return (d.vm === 'M' || d.vm === 'E') && d.ve != null && !this.nearlyReported(d, metric);
    },

    // The estimated part is tiny: the 90% range is under EST_MIN_REL_WIDTH of the estimate.
    // Such rows are shown as reported (no est mark, no dotted line, not in the estimated share).
    nearlyReported(d, metric = STATE.metric) {
        if (!d || d.src === 'e') return false;
        const v = metric === 'weight' ? d.we : d.ve;
        const lo = metric === 'weight' ? d.wlo : d.vlo, hi = metric === 'weight' ? d.whi : d.vhi;
        return v > 0 && lo != null && hi != null && (hi - lo) / v < EST_MIN_REL_WIDTH;
    },

    // 90% interval of the metric value, when the flow is an estimate.
    interval(d, metric = STATE.metric) {
        if (!this.isEst(d, metric)) return null;
        const lo = metric === 'weight' ? d.wlo : d.vlo, hi = metric === 'weight' ? d.whi : d.vhi;
        return lo != null && hi != null ? [lo, hi] : null;
    },

    async loadAllYears(product = STATE.product) {
        const years = this.productYears(product);
        const res = await Promise.all(years.map(y => this.loadFlows(product, y)));
        return Object.fromEntries(years.map((y, k) => [y, res[k]]));
    },

    async loadSummary(product = STATE.product) {
        if (this._summary[product]) return this._summary[product];
        const k = `summary|${product}`;
        const js = await (this._pending[k] ||= fetch(`data/summary/${product}.json`).then(r => r.json()).finally(() => { delete this._pending[k]; }));
        this._summary[product] = js;
        return js;
    },

    async loadVisibility() {
        if (!this._visibility) this._visibility = await (this._pending.vis ||= fetch('data/visibility.json').then(r => r.json()).finally(() => { delete this._pending.vis; }));
        return this._visibility;
    },

    // ── reporting status
    reported(iso, year, flow) {
        const s = STATE.meta.reporting[iso]?.[String(year)] || '';
        return s.includes(flow);
    },

    presetMembers(preset = STATE.preset) {
        return STATE.meta.presets[preset]?.members || null;
    },

    inRegion(iso, region = STATE.region) {
        if (!region || region === 'Global') return true;
        return STATE.eco[iso]?.reg === REGION_CODE[region];
    },

    // Metric value of a flow; null when the chosen record has no weight.
    val(d, metric = STATE.metric) {
        return flowVal(d, metric);
    },

    // ── scope and top-N filtering
    // Scope rules:
    //   preset (JAI / SAS): flows with at least one end in the preset
    //   region (Global preset only, SHC rule): both ends in the region
    //   selected country: flows that touch it
    filterData(flows) {
        const members = this.presetMembers();
        const mset = members ? new Set(members) : null;
        const sel = STATE.selectedCountry;
        let scope = flows.filter(d => {
            if (mset && !(mset.has(d.e) || mset.has(d.i))) return false;
            if (!mset && STATE.region !== 'Global' && !(this.inRegion(d.e) && this.inRegion(d.i))) return false;
            if (sel && d.e !== sel && d.i !== sel) return false;
            return true;
        });
        STATE.scopeFlows = scope;

        const withVal = scope.filter(d => {
            const v = this.val(d);
            return v != null && v > 0 && STATE.flowFilters.has(d.fc);
        });
        const top = withVal.slice().sort((a, b) => this.val(b) - this.val(a)).slice(0, STATE.topN);
        STATE.filteredData = top;
        STATE.nodeStats = this.nodeTotals(scope);
        return top;
    },

    // Node size: total exports + imports of each economy within the current scope (spec 7.2).
    nodeTotals(scope) {
        const s = {};
        scope.forEach(d => {
            const v = this.val(d);
            if (v == null || v <= 0) return;
            (s[d.e] ||= { exp: 0, imp: 0 }).exp += v;
            (s[d.i] ||= { exp: 0, imp: 0 }).imp += v;
        });
        Object.values(s).forEach(o => { o.total = o.exp + o.imp; });
        return s;
    },
};
